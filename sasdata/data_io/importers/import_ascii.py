# Dataset types that the columns in a header line are matched against, in order of preference.
all_dataset_types = [one_dim, two_dim, three_dim, angle_dim, sesans]


class AsciiSeparator(Enum):
    Comma = (0,)
    Whitespace = (1,)
    Tab = 2


# TODO: Turn them all of for now so the caller can turn one of them on. But is this the desired behaviour?
def initialise_separator_dict(initial_value: bool = False) -> dict[str, bool]:
    return {"Whitespace": initial_value, "Comma": initial_value, "Tab": initial_value}


@dataclass
class AsciiReaderParams:
    """This object contains the parameters that are used to load a series of
    ASCII files. These parameters can be generated by the ASCII Reader Dialog
    when using SasView."""

    # These will be the FULL file path. Will need to convert to basenames for some functions.
    filenames: list[str]
    # The unit object for the column should only be None if the column is <ignore>!
    columns: list[tuple[str, NamedUnit | None]]
    metadata: AsciiReaderMetadata = field(default_factory=AsciiReaderMetadata)
    starting_line: int = 0
    excluded_lines: set[int] = field(default_factory=set)
    separator_dict: dict[str, bool] = field(default_factory=initialise_separator_dict)
    # Take a copy in case its mutated (which it shouldn't be)
    dataset_type: DatasetType = field(default_factory=lambda: replace(one_dim))

    def __post_init__(self):
        self.initialise_metadata()

    def initialise_metadata(self):
        for filename in self.filenames:
            basename = path.basename(filename)
            if basename not in self.metadata.filename_separator:
                self.metadata.filename_separator[basename] = "_"
                self.metadata.filename_specific_metadata[basename] = {}

    @staticmethod
    def is_column_included(column: tuple[str, NamedUnit | None]) -> bool:
        """Whether a column is loaded, i.e. it isn't ignored and has a unit."""
        return column[0] != "<ignore>" and isinstance(column[1], NamedUnit)

    @property
    def columns_included(self) -> list[tuple[str, NamedUnit]]:
        return [column for column in self.columns if self.is_column_included(column)]

    @property
    def column_positions_included(self) -> list[int]:
        """Position in each line of the columns in columns_included. Ignored columns still take up a position."""
        return [position for position, column in enumerate(self.columns) if self.is_column_included(column)]


def guess_params_from_filename(filename: str, dataset_type: DatasetType) -> AsciiReaderParams:
    # Lets just assume we want all separators on. This seems to work for most files.
    separator_dict = initialise_separator_dict(True)
    with open(filename) as file:
        lines = file.readlines()
        lines_split = [split_line(separator_dict, line) for line in lines]
        startpos = guess_starting_position(lines_split)
        colcount = guess_column_count(lines_split, startpos)
        header = find_column_header(lines_split, startpos, colcount)
        if header is not None:
            # The file names its columns, so use those (and their units) instead of guessing.
            columns, dataset_type = header
        else:
            # Columns we don't know the unit for are ignored. They are kept as <ignore> rather than removed, so the
            # columns after them still line up with the data.
            columns = [
                (x, get_default_unit(x, unit_kinds[x])) if x in unit_kinds else ("<ignore>", None)
                for x in guess_columns(colcount, dataset_type)
            ]
            dataset_type = guess_dataset_type(filename)
        params = AsciiReaderParams(
            [filename],
            columns,
            starting_line=startpos,
            separator_dict=separator_dict,
            dataset_type=dataset_type,
        )
        return params


# Every column name that can appear in a dataset, which may be used to name columns in a header line.
KNOWN_COLUMNS = set(unit_kinds) | {
    column for dataset in all_dataset_types for column in dataset.required + dataset.optional
}

# A column heading: a name optionally followed by units in brackets, e.g. 'Q', 'Q(Ang^-1)', 'I[cm^-1]'.
COLUMN_HEADING = re.compile(r"^(?P<name><ignore>|[A-Za-z][A-Za-z0-9_]*)(?:\((?P<unit>[^()]*)\)|\[(?P<bracket_unit>[^\]]*)\])?$")


def parse_column_header(tokens: list[str]) -> tuple[list[tuple[str, NamedUnit | None]], DatasetType] | None:
    """
    Try to read a line of tokens as column headings, each of which is the name of a quantity optionally followed by
    its units, e.g. ``Q(Ang^-1) I(cm^-1) dI(cm^-1)``. Columns named ``<ignore>`` are skipped.

    :return: The columns and the dataset type they make up, or None if the tokens are not all recognised headings.
    """
    tokens = [token for token in tokens if token]
    if tokens and tokens[0].startswith("#"):
        tokens[0] = tokens[0].lstrip("#")
        tokens = [token for token in tokens if token]
    columns: list[tuple[str, NamedUnit | None]] = []
    for token in tokens:
        match = COLUMN_HEADING.match(token)
        if match is None:
            return None
        name = match.group("name")
        if name == "<ignore>":
            columns.append((name, None))
            continue
        if name not in KNOWN_COLUMNS:
            return None
        unit_string = match.group("unit") or match.group("bracket_unit")
        if unit_string:
            try:
                unit = unit_parser.parse(unit_string.strip())
            except Exception:
                return None
        elif name in unit_kinds:
            unit = get_default_unit(name, unit_kinds[name])
        else:
            unit = units.none
        if not isinstance(unit, NamedUnit):
            return None
        columns.append((name, unit))

    names = [name for name, _ in columns if name != "<ignore>"]
    if len(set(names)) != len(names):
        return None
    for dataset_type in all_dataset_types:
        if all(name in names for name in dataset_type.required) and \
                all(name in dataset_type.required + dataset_type.optional for name in names):
            return columns, replace(dataset_type)
    return None


def find_column_header(lines_split: list[list[str]], startpos: int, colcount: int) \
        -> tuple[list[tuple[str, NamedUnit | None]], DatasetType] | None:
    """Look back through the lines before the data for one that names each column."""
    for line in reversed(lines_split[:startpos]):
        tokens = [token for token in line if token]
        if tokens and tokens[0] == "#":
            tokens = tokens[1:]
        if len(tokens) != colcount:
            continue
        header = parse_column_header(tokens)
        if header is not None:
            return header
    return None


def split_line(separator_dict: dict[str, bool], line: str) -> list[str]:
    """Split a line in a CSV file based on which seperators the user has
    selected on the widget.

    """
    expr = ""
    for seperator, isenabled in separator_dict.items():
        if isenabled:
            if expr != r"":
                expr += r"|"
            match seperator:
                case "Comma":
                    seperator_text = r","
                case "Whitespace":
                    seperator_text = r"\s+"
                case "Tab":
                    seperator_text = r"\t"
            expr += seperator_text

    return re.split(expr, line.strip())


# TODO: Implement error handling.
def load_quantities(params: AsciiReaderParams, filename: str, metadata: Metadata) -> dict[str, Quantity]:
    """Load a list of quantities from the filename based on the params.

    Only the lines that will actually be used become data points. A line is skipped if it is before
    ``params.starting_line``, if its (0-based) line number is in ``params.excluded_lines``, or if it can't be read as a
    row of numbers (e.g. blank lines, comments, or lines with too few columns). Skipped lines are left out entirely
    rather than being stored as zeros.
    """
    with open(filename) as ascii_file:
        lines = ascii_file.readlines()

    # Ignored columns are skipped, but still count when finding the position of the other columns in each line.
    positions = params.column_positions_included
    column_count = len(positions)
    required_length = max(positions) + 1 if positions else 0
    rows: list[list[float]] = []
    for i, current_line in enumerate(lines):
        if i < params.starting_line or i in params.excluded_lines:
            continue
        line_split = split_line(params.separator_dict, current_line)
        # Values after the last loaded column (e.g. an empty string at the end of the line, or extra columns) and in
        # ignored columns aren't read, so they don't need to be numbers.
        if len(line_split) < required_length:
            logger.info(f"{path.basename(filename)}: line {i + 1} skipped as it has too few columns.")
            continue
        try:
            # TODO: Values are parsed as floats; decimal commas, Fortran 'D' exponents and non-numeric columns (e.g. a
            # boolean mask) are not handled and cause the row to be skipped.
            rows.append([float(line_split[position]) for position in positions])
        except ValueError:
            # If any of the lines contain non-numerical data, then this line can't be read in as a quantity so it
            # should be ignored entirely.
            logger.info(f"{path.basename(filename)}: line {i + 1} skipped as it contains non-numerical data.")

    data = np.array(rows, dtype=float).reshape(len(rows), column_count)
    file_quantities = {
        name: NamedQuantity(name, data[:, j].copy(), unit, id_header=metadata.id_header)
        for j, (name, unit) in enumerate(params.columns_included)
    }
    return file_quantities


def import_metadata(metadata: dict[str, AsciiMetadataCategory[str]]) -> MetaNode:
    root_contents = []
    for top_level_key, top_level_item in metadata.items():
        children = []
        for metadatum_name, metadatum in top_level_item.values.items():
            children.append(MetaNode(name=metadatum_name, attrs={}, contents=metadatum))
        if top_level_key == "other":
            root_contents.extend(children)
        else:
            group = MetaNode(name=top_level_key, attrs={}, contents=children)
            root_contents.append(group)
    return MetaNode(name="root", attrs={}, contents=root_contents)


def merge_uncertainties(quantities: dict[str, Quantity]) -> dict[str, Quantity]:
    """Data in the ASCII files will have the uncertainties in a separate column.
    This function will merge columns of data with the columns containing their
    uncertainties so that both are in one Quantity object."""
    new_quantities: dict[str, Quantity] = {}
    error_quantity_names = pairings.values()
    for name, quantity in quantities.items():
        if name in error_quantity_names:
            continue
        pairing = bidirectional_pairings.get(name, "")
        error_quantity = None
        for other_name, other_quantity in quantities.items():
            if other_name == pairing:
                error_quantity = other_quantity
        if error_quantity is not None:
            to_add = quantity.with_standard_error(error_quantity)
        else:
            to_add = quantity
        new_quantities[name] = to_add
    return new_quantities


def load_measurements(params: AsciiReaderParams) -> list[SasMeasurement]:
    """
    This loads a series of SasMeasurement objects based on the params.
    The amount of SasMeasurement objects loaded will depend on how many
    filenames are present in the list contained in the params.
    """
    loaded_data: list[SasMeasurement] = []
    for filename in params.filenames:
        raw_metadata = import_metadata(
            params.metadata.all_file_metadata(path.basename(filename))
        )
        metadata = Metadata(
            title=None,
            run=[],
            definition=None,
            sample=None,
            instrument=None,
            process=None,
            magnetic=None,
            raw=raw_metadata,
        )
        quantities = load_quantities(params, filename, metadata)
        data = SasMeasurement(
            path.basename(filename),
            merge_uncertainties(quantities),
            params.dataset_type,
            metadata,
        )
        loaded_data.append(data)
    return loaded_data


class AsciiImporter(Importer):
    """
    Importer for column-based ASCII files.

    The importer can be given an :class:`AsciiReaderParams` object (e.g. generated by the ASCII Reader Dialog in
    SasView) describing how to read the file(s). If no parameters are given, they are guessed from the file contents.
    As almost any text file can be read as ASCII, this importer is the fallback used when no other importer recognises
    a file, so it is tested last.
    """

    name = "ASCII"
    priority = 1000

    def __init__(self, config: dict | None = None, params: AsciiReaderParams | None = None):
        super().__init__(config)
        self.params = params

    @classmethod
    def can_import(cls, source: Source_Type) -> bool:
        """Any text file on disk could be a column-based ASCII file."""
        if not isinstance(source, (str, Path)):
            return False
        return is_text(read_header(source))

    def load_data(self, source: Source_Type | None = None) -> dict[str, SasMeasurement]:
        """
        Load ASCII data, keyed by the basename of each file.

        :param source: The file to load. If parameters were given to the importer, they are used to read this file;
            otherwise, the parameters are guessed from the file contents. If ``source`` is None, every file listed in
            the importer's parameters is loaded.
        """
        if source is None:
            if self.params is None:
                raise ValueError("A file to load, or AsciiReaderParams listing the files to load, must be given.")
            params = self.params
        elif not isinstance(source, (str, Path)):
            raise TypeError("The ASCII importer can only load files from a path.")
        elif self.params is not None:
            params = replace(self.params, filenames=[str(source)])
        else:
            filename = str(source)
            params = guess_params_from_filename(filename, guess_dataset_type(filename))
        return measurements_by_name(load_measurements(params))
